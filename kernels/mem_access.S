/*
 * mem_access.S — 字节/半字访存全覆盖测试 (LB, LH, LW, LBU, LHU, SB, SH, SW)
 *
 * 输入:  VRAM[0x100000] = {0x7F, 0x80, 0xFF, 0x00, 0x1234, 0x5678}
 *        字节: [0x00, 0x7f, 0x80, 0xff, 0x34, 0x12, 0x78, 0x56]
 *        (小端序)
 * 输出:  VRAM[0x300000] = 7 个 uint32_t 结果
 *
 * 内存布局:
 *   VRAM[0x100000] = 输入 (8 字节原始数据)
 *   VRAM[0x300000] = 输出数组
 *   VRAM[0x400000] = kernel 代码
 */

.text
.globl _start
_start:
    /* 基地址 */
    lw   t0, 0x80(zero)          /* t0 = 0x100000 (输入) */
    lw   t1, 0x88(zero)          /* t1 = 0x300000 (输出) */

    /* ================================================================
     * 读取测试
     * 输入布局 (小端):
     *   offset 0: 0x7F = 127  (正数)
     *   offset 1: 0x80 = -128 (有符号), 128 (无符号)
     *   offset 2: 0xFF = -1   (有符号), 255 (无符号)
     *   offset 3: 0x00
     *   offset 4-5: 0x1234 (小端: 0x34 0x12)
     *   offset 6-7: 0x5678 (小端: 0x78 0x56)
     * ================================================================ */

    /* 1. LB — 符号扩展 */
    lb   t2, 0(t0)          /* t2 = (int8_t)0x7F = 127 */
    sw   t2, 0(t1)

    lb   t2, 1(t0)          /* t2 = (int8_t)0x80 = -128 */
    sw   t2, 4(t1)

    lb   t2, 2(t0)          /* t2 = (int8_t)0xFF = -1 */
    sw   t2, 8(t1)

    /* 2. LBU — 零扩展 */
    lbu  t2, 1(t0)          /* t2 = (uint8_t)0x80 = 128 */
    sw   t2, 12(t1)

    lbu  t2, 2(t0)          /* t2 = (uint8_t)0xFF = 255 */
    sw   t2, 16(t1)

    /* 3. LH — 有符号半字 */
    lh   t2, 4(t0)          /* t2 = (int16_t)0x1234 = 4660 */
    sw   t2, 20(t1)

    lh   t2, 6(t0)          /* t2 = (int16_t)0x5678 = 22136 */
    sw   t2, 24(t1)

    /* 4. LHU — 无符号半字 */
    lhu  t2, 4(t0)          /* t2 = (uint16_t)0x1234 = 4660 */
    sw   t2, 28(t1)

    /* 5. LW — 字加载 (验证基础) */
    lw   t2, 0(t0)          /* t2 = 0x8000007F */
    sw   t2, 32(t1)

    /* ================================================================
     * 写入测试: SB, SH, SW
     * 写入到输出区后部，然后读回验证
     * ================================================================ */
    /* SB: 写入 0x42 到 offset 256 */
    addi t2, zero, 0x42
    sb   t2, 256(t1)        /* *(uint8_t*)(0x300000+256) = 0x42 */
    lb   t3, 256(t1)        /* 读回 */
    sw   t3, 36(t1)          /* 存储读回的值 */

    /* SH: 写入 0x4321 到 offset 260 */
    lui  t2, 0x4
    addi t2, t2, 0x321       /* t2 = 0x4321 */
    sh   t2, 260(t1)
    lh   t3, 260(t1)         /* 读回 */
    sw   t3, 40(t1)

    /* SW: 存入已知值并读回验证 */
    lw   t2, 0(t0)        /* t2 = 0x8000007F (从输入) */
    sw   t2, 264(t1)      /* 写入 */
    lw   t3, 264(t1)      /* 读回 */
    sw   t3, 44(t1)

    ebreak
